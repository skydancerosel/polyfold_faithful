#!/usr/bin/env python3
"""Tiered reviewer checklist from the trusted-base extraction.

usage (from the project folder, after `lake env lean Exposition/checklist/TrustedBase.lean`):
    python3 Exposition/checklist/build_checklist.py

mains.tsv labels are "tier|Thm x.y.z".  A definition row belongs to the first tier (in the order
of the JSON) whose main statements reach one of its constants.  The row cover is the one of
report.py: theorem rows first, then a greedy cover by rows of the constant's own or an earlier
chapter.
"""
import json, re, collections, sys, os
sys.setrecursionlimit(100000)
HERE = os.path.dirname(os.path.abspath(__file__))
D_, SPEC, OUT = HERE, os.path.join(HERE, 'mains.json'), os.path.join(os.path.dirname(HERE), 'ReviewerChecklist.md')
CMP = os.path.join(os.path.dirname(HERE), 'cmp', 'ch%02d.json')
spec = json.load(open(SPEC))
tiers = [t['key'] for t in spec['tiers']]
rows = {}; decl2rows = collections.defaultdict(list); rowidx = {}
for n in range(1, 12):
    for x in json.load(open(CMP % n))['items']:
        rowidx[x['id']] = len(rows); rows[x['id']] = x
        for d in x['lean'].get('decls', []):
            decl2rows['Polyfold.' + d.split(' · ')[1].strip()].append(x['id'])
graph = {}; kind = {}; mod = {}
for line in open(os.path.join(D_, 'graph.tsv')):
    if line.strip():
        p, k, m, ds = line.rstrip('\n').split('\t'); graph[p] = ds.split() if ds else []; kind[p] = k; mod[p] = m
mains = []
for line in open(os.path.join(D_, 'mains.tsv')):
    if line.strip():
        lab, nm, k, m, ds = line.rstrip('\n').split('\t')
        tier, lab = lab.split('|', 1)
        mains.append((tier, lab, nm, m, ds.split() if ds else []))
short = lambda n: n[len('Polyfold.'):] if n.startswith('Polyfold.') else n
fileof = lambda m: m.replace('Polyfold.', '', 1).replace('.', '/') + '.lean'
chap = lambda rid: int(rid[1:].split('.')[0])
reach = collections.defaultdict(set)      # constant -> set of (tier, label)
for tier, lab, nm, m, ds in mains:
    st = list(ds); seen = set()
    while st:
        x = st.pop()
        if x in seen: continue
        seen.add(x); st += graph.get(x, [])
    for x in seen: reach[x].add((tier, lab))
num = lambda lab: lab.split()[1]
thmrows = collections.OrderedDict()
for tier, lab, nm, m, ds in mains:
    rs = decl2rows.get(nm, [])
    pick = [r for r in rs if re.search(r'(Theorem|Corollary|Proposition) ' + re.escape(num(lab)) + r'\b', rows[r]['book']['label'])] or rs
    pick = [r for r in pick if 'proof of' not in rows[r]['book']['label']] or pick
    for r in pick: thmrows.setdefault(r, set()).add((tier, lab, nm))
mapped = {x for x in reach if x in decl2rows}
modchap = lambda x: int(re.match(r'Polyfold\.Chapter(\d+)', mod[x]).group(1))
cand = {x: ([r for r in decl2rows[x] if chap(r) <= modchap(x)] or decl2rows[x]) for x in mapped}
assign = {}
for x in mapped:
    t = [r for r in cand[x] if r in thmrows]
    if t: assign[x] = min(t, key=lambda r: rowidx[r])
left = {x for x in mapped if x not in assign}
while left:
    cnt = collections.Counter(r for x in left for r in cand[x])
    best = max(cnt, key=lambda r: (cnt[r], 'Definition' in rows[r]['book']['label'], -rowidx[r]))
    for x in [x for x in left if best in cand[x]]: assign[x] = best; left.discard(x)
row_nodes = collections.defaultdict(set)
for x, r in assign.items(): row_nodes[r].add(x)
# row dependency order
rg = collections.defaultdict(set)
for x, r in assign.items():
    for d in graph.get(x, []):
        if d in assign and assign[d] != r: rg[r].add(assign[d])
allrows = sorted(row_nodes, key=lambda r: rowidx[r])
index = {}; low = {}; st = []; on = set(); order = []; c = [0]
def tarjan(v):
    index[v] = low[v] = c[0]; c[0] += 1; st.append(v); on.add(v)
    for w in sorted(rg[v], key=lambda r: rowidx[r]):
        if w not in index: tarjan(w); low[v] = min(low[v], low[w])
        elif w in on: low[v] = min(low[v], index[w])
    if low[v] == index[v]:
        comp = []
        while True:
            w = st.pop(); on.discard(w); comp.append(w)
            if w == v: break
        order.append(sorted(comp, key=lambda r: rowidx[r]))
for v in allrows:
    if v not in index: tarjan(v)
pos = {r: i for i, comp in enumerate(order) for r in comp}
def row_tier(r):
    ts = {t for x in row_nodes[r] for (t, _) in reach[x]}
    return min(ts, key=tiers.index)
unmapped = sorted((x for x in reach if x not in decl2rows), key=lambda x: (mod[x], x))
unm_tier = {x: min({t for t, _ in reach[x]}, key=tiers.index) for x in unmapped}

def esc(s): return s.replace('|', '\\|')
def booklab(r):
    b = rows[r]['book']; return esc(b['label'])
out = []; w = out.append
tot_rows = set(allrows) | set(thmrows)
w('# Reviewer checklist\n\n')
w('*Generated by `Exposition/checklist/build_checklist.py` from the Lean environment (`Exposition/checklist/TrustedBase.lean`) and the comparison pages; do not edit by hand.*\n\n')
w('Lean checks every proof. What it cannot check is whether the definitions and the statements say what the book '
  'says. This page lists exactly those items, in tiers: a reviewer who signs off a tier checks its statements and '
  'its definition rows, and nothing else. Each row id (V3.14, …) is an entry of the comparison page '
  '(`Exposition/Comparison.md`, or `polyfold-beside-lean.html` in a browser), which gives the book text in '
  'paraphrase, the Lean declarations and the verdict.\n\n'
  'The readings the formalization had to choose (sc-smooth germs on neighbourhoods that may shrink with the level, '
  'the tame reading of "tame strong bundle", …) are part of these definitions; the README lists them under '
  '*What a reviewer is most needed for*, and `Findings.md` gives the reason for each.\n\n')
w('## Before reading: the machine checks\n\n')
w('```bash\nlake build Polyfold\n```\n\n```bash\nlake env lean Polyfold/Test.lean\n```\n\n'
  'The second command prints the axioms of every theorem; each must list only `propext`, `Classical.choice` and '
  '`Quot.sound` (or a subset). No `sorryAx`, no project axioms.\n\n')
w('## Tiers\n\n| Tier | Statements | New definition rows | Lean helper constants without a row |\n|---|---|---|---|\n')
for t in spec['tiers']:
    k = t['key']
    ns = len({lab for (tt, lab, nm, m, ds) in mains if tt == k})
    nr = sum(1 for r in allrows if row_tier(r) == k and r not in thmrows)
    nu = sum(1 for x in unmapped if unm_tier[x] == k)
    w(f"| {t['title']} | {ns} | {nr} | {nu} |\n")
w('\nA later tier assumes the earlier ones: its definition rows are only those its statements need beyond the '
  'earlier tiers.\n\n')
for t in spec['tiers']:
    k = t['key']
    w(f"## {t['title']}\n\n### Statements\n\n| Book | Lean declaration | Comparison row |\n|---|---|---|\n")
    seen = collections.OrderedDict()
    for (tt, lab, nm, m, ds) in mains:
        if tt != k: continue
        rs = sorted({r for r, v in thmrows.items() if any(a == tt and b == lab and c == nm for a, b, c in v)}, key=lambda r: rowidx[r])
        w(f"| {lab} | `{short(nm)}` ({fileof(m)}) | {', '.join(rs) or '—'} |\n")
    defs = sorted((r for r in allrows if row_tier(r) == k and r not in thmrows), key=lambda r: (chap(r), pos[r]))
    w(f"\n### Definition rows ({len(defs)}), in dependency order\n\n| Row | Book | Lean declarations used by the statements |\n|---|---|---|\n")
    for r in defs:
        ds = sorted(short(x) for x in row_nodes[r])
        shown = ', '.join(f'`{d}`' for d in ds[:4]) + (f' and {len(ds) - 4} more' if len(ds) > 4 else '')
        w(f"| {r} | {booklab(r)} | {shown} |\n")
    um = [x for x in unmapped if unm_tier[x] == k]
    if um:
        w(f"\n<details><summary>{len(um)} helper constants without a row of their own (accessors, coercions, instances)</summary>\n\n")
        byf = collections.defaultdict(list)
        for x in um: byf[fileof(mod[x])].append(short(x))
        for f, xs in sorted(byf.items()):
            w(f"* {f}: " + ', '.join(f'`{x}`' for x in xs) + '\n')
        w('\n</details>\n')
    w('\n')
if spec.get('mathlib'):
    w('## Optional: conclusions in Mathlib\'s language\n\n'
      'These state the solution-set conclusions with Mathlib\'s `IsManifold` (with the orientation, for Theorem 6.6.18; or the project\'s submanifold notion, '
      'for Theorem 3.6.8), so a reviewer who prefers Mathlib\'s manifolds with corners can check them instead of the '
      'project\'s corner-structure definitions.\n\n| Book | Lean declaration |\n|---|---|\n')
    for lab, nm in spec['mathlib']:
        w(f"| {lab} | `{short(nm)}` |\n")
open(OUT, 'w').write(''.join(out))
print('rows', len(tot_rows), 'defrows', len([r for r in allrows if r not in thmrows]), 'unmapped', len(unmapped))
for t in tiers:
    print(t, sum(1 for r in allrows if row_tier(r) == t and r not in thmrows))
